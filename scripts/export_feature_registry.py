"""Write apps/web/src/lib/feature-registry.generated.ts from the Python feature registry (F0.7).

Run:  python scripts/export_feature_registry.py          (rewrites the file)
      python scripts/export_feature_registry.py --check  (exit 1 when the file is out of date; used by tests)
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "services/api/src"))
from campus247.features.registry import FEATURES  # noqa: E402

TARGET = ROOT / "apps/web/src/lib/feature-registry.generated.ts"


def render() -> str:
    keys = [f.key for f in FEATURES if f.client_visible]
    defaults = {f.key: (f.default_value if f.variants else f.default) for f in FEATURES if f.client_visible}
    nav = {n: f.key for f in FEATURES if f.client_visible for n in f.nav_keys}
    pages = {p: f.key for f in FEATURES if f.client_visible for p in f.pages}
    lines = ["// Generated by scripts/export_feature_registry.py from campus247/features/registry.py. Do not edit.",
             "export const FEATURE_KEYS = " + json.dumps(keys, indent=2) + " as const;",
             "export type FeatureKey = (typeof FEATURE_KEYS)[number];",
             "export const FEATURE_DEFAULTS: Record<FeatureKey, boolean | string> = " + json.dumps(defaults, indent=2) + ";",
             "export const NAV_FEATURE: Record<string, FeatureKey> = " + json.dumps(nav, indent=2) + ";",
             "export const PAGE_FEATURE: Record<string, FeatureKey> = " + json.dumps(pages, indent=2) + ";", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        sys.exit(0 if TARGET.is_file() and TARGET.read_text(encoding="utf-8").replace("\r\n", "\n") == text else 1)
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    print("wrote", TARGET.relative_to(ROOT))
