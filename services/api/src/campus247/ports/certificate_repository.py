"""Transactional port for document drafts, confirmation, replay and audit."""
from __future__ import annotations

from contextlib import AbstractContextManager
from typing import Any, Protocol


class CertificateTransaction(Protocol):
    def get(self, document_id: str) -> dict[str, Any] | None: ...
    def list(self, owner: str | None) -> list[dict[str, Any]]: ...
    def save(self, record: dict[str, Any]) -> None: ...
    def replay(self, actor: str, key: str) -> dict[str, Any] | None: ...
    def complete(self, actor: str, key: str, fingerprint: str, result: dict[str, Any]) -> None: ...
    def audit(self, event: dict[str, Any]) -> None: ...


class CertificateRepository(Protocol):
    def transaction(self) -> AbstractContextManager[CertificateTransaction]: ...
